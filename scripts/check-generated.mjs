// Are the generated browser copies in step with their sources?
//
// site/resolve.js and site/share.js are produced by scripts/build.mjs from
// scripts/lib/resolve.mjs and scripts/lib/share.mjs. Editing a source and committing
// without rebuilding ships a page whose logic disagrees with the exports and the CLI —
// which on this project has repeatedly meant the figures shown not matching the GPX
// downloaded. Cheap to check, so the pre-commit hook checks it.
//
// Exits non-zero if anything is stale or missing.
//
// Usage: node scripts/check-generated.mjs

import fs from 'node:fs';

// Must mirror generateForBrowser() in scripts/build.mjs.
const GENERATED = [
  { source: 'scripts/lib/resolve.mjs', out: 'site/resolve.js', exposed: ['resolveSelection', 'dayWindow'] },
  {
    source: 'scripts/lib/share.mjs',
    out: 'site/share.js',
    exposed: [
      'canonicalIds',
      'fingerprint',
      'encodeSelection',
      'decodeSelection',
      'encodeShare',
      'decodeShare',
    ],
  },
];

const expected = ({ source, exposed }) => {
  const code = fs
    .readFileSync(source, 'utf8')
    .replace(/^export (function|const)/gm, '$1')
    .trimEnd();
  return (
    `// GENERATED by scripts/build.mjs from ${source} — do not edit.\n${code}\n` +
    `${exposed.map((n) => `window.${n} = ${n};`).join('\n')}\n`
  );
};

const problems = [];
for (const entry of GENERATED) {
  if (!fs.existsSync(entry.out)) {
    problems.push(`${entry.out} is missing — run npm run build`);
    continue;
  }
  if (fs.readFileSync(entry.out, 'utf8') !== expected(entry)) {
    problems.push(`${entry.out} is stale relative to ${entry.source} — run npm run build`);
  }
}

if (problems.length) {
  for (const p of problems) process.stderr.write(`${p}\n`);
  process.exit(1);
}
process.stdout.write(`${GENERATED.length} generated file(s) match their sources\n`);
